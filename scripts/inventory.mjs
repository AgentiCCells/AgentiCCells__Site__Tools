// Inventory: regenerate data/inventory.json from each tool's manifest.json in SGraph-AI__Tools.
// Usage: node scripts/inventory.mjs <path to a checkout of the-cyber-boardroom/SGraph-AI__Tools>
// The checkout must be at the pinned commit below; the script refuses any other.
// A tool is a sgraph_ai_tools__static/tools/v0/v0.1/v<version>/<locale>/<folder>/manifest.json that has a
// "slug". Where a slug appears in several versions, the highest version wins. Manifests without a slug
// (release manifests, and two tool folders that use "id") are listed under "skipped" with the reason.
// Written by conductor.tools@AgentiCCells.dinis, 2026-11-20. Node built-ins only. Apache-2.0.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

export const UPSTREAM = 'https://github.com/the-cyber-boardroom/SGraph-AI__Tools';
export const PINNED = 'a905a5ca'; // cells.b@ read a905a5c (brief, 19 Nov 2026); full id checked below
const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/inventory.mjs <SGraph-AI__Tools checkout>'); process.exit(2); }
const git = (...a) => execFileSync('git', ['-C', dir, ...a], { encoding: 'utf8' }).trim();
const head = git('rev-parse', 'HEAD');
if (!head.startsWith(PINNED)) { console.error(`checkout is at ${head.slice(0, 8)}, not the pinned ${PINNED}`); process.exit(1); }
const files = git('ls-files', '--', 'sgraph_ai_tools__static/tools').split('\n').filter((f) => f.endsWith('/manifest.json'));
const cmp = (a, b) => { const x = a.split('.').map(Number), y = b.split('.').map(Number); for (let i = 0; i < 3; i++) if (x[i] !== y[i]) return x[i] - y[i]; return 0; };
const best = new Map(); const skipped = [];
for (const f of files) {
  const m = JSON.parse(readFileSync(join(dir, f), 'utf8'));
  const parts = f.split('/'); const version = (parts[4] || '').replace(/^v/, '');
  if (!m.slug) { skipped.push({ manifest: f, reason: m.id ? 'tool folder uses "id", not "slug"' : 'release manifest, not a tool' }); continue; }
  const prev = best.get(m.slug);
  if (!prev || cmp(version, prev.folder_version) > 0) best.set(m.slug, { m, f, folder_version: version });
}
const tools = [...best.values()].sort((a, b) => a.m.slug.localeCompare(b.m.slug)).map(({ m, f, folder_version }) => ({
  slug: m.slug, name: m.name, description: m.description, status: m.status || 'unknown',
  category: String(m.category || 'unknown').toLowerCase(), version: folder_version, keywords: m.keywords || [],
  manifest: `${UPSTREAM}/blob/${head}/${f}`,
}));
const out = { about: 'Generated by scripts/inventory.mjs from each tool\'s manifest.json. Do not edit by hand.', source: UPSTREAM, commit: head, generated_from: 'sgraph_ai_tools__static/tools/**/manifest.json', count: tools.length, tools, skipped };
writeFileSync('data/inventory.json', JSON.stringify(out, null, 2) + '\n');
console.log(`data/inventory.json: ${tools.length} tools, ${skipped.length} manifests skipped, from ${head.slice(0, 7)}`);
